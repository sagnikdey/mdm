// Builds src/generated.css from tokens.json (DTCG). Run: node scripts/build.mjs
// Tier 1 (primitives) -> --sg-<ramp>-<step>. Tier 2 (semantic) -> --sg-<group>-<name>, with Light/Dark modes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const tokens = JSON.parse(readFileSync(root + "tokens.json", "utf8"));

// hex -> oklch (CSS Color 4 reference math)
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
function oklch(hex) {
  const h = hex.slice(1);
  const [r, g, b] = [0, 2, 4].map((i) => lin(parseInt(h.slice(i, i + 2), 16) / 255));
  const a = h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1;
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const C = Math.hypot(A, B);
  let H = (Math.atan2(B, A) * 180) / Math.PI;
  if (H < 0) H += 360;
  const f = (n, d) => +n.toFixed(d);
  return `oklch(${f(L, 3)} ${f(C, 3)} ${C < 0.002 ? 0 : f(H, 1)}${a < 1 ? ` / ${f(a, 3)}` : ""})`;
}

const rem = (px) => (px === 0 ? "0" : px === 9999 ? "9999px" : `${+(px / 16).toFixed(4)}rem`);
const em = (px, size) => (px === 0 ? "0" : `${+(px / size).toFixed(4)}em`);
const name = (path) => "--sg-" + path.join("-");
// {primitives.color.blue.600} -> var(--sg-blue-600)
const ref = (s) => {
  const p = s.slice(1, -1).split(".");
  const tier = p.shift();
  if (tier === "primitives" && p[0] === "color") p.shift();
  return `var(${name(p)})`;
};

function walk(node, path = [], out = []) {
  if (node && typeof node === "object" && "$value" in node) out.push([path, node]);
  for (const [k, v] of Object.entries(node ?? {})) if (!k.startsWith("$") && typeof v === "object") walk(v, [...path, k], out);
  return out;
}
const val = (tok, path) => {
  const v = tok.$value;
  if (typeof v === "string" && v.startsWith("{")) return ref(v);
  if (tok.$type === "color") return oklch(v);
  if (tok.$type === "fontFamily") return `"${v}", ${v.includes("Mono") ? "ui-monospace, monospace" : "ui-sans-serif, system-ui, sans-serif"}`;
  if (tok.$type === "dimension") return v;
  return v;
};

const L = [];
const light = [], dark = [];
const P = tokens.primitives;

// Tier 1
L.push("/* Generated by scripts/build.mjs from tokens.json. Do not edit by hand. */", "", "/* Tier 1: primitives. Raw values, never used by components directly. */", ":root {");
for (const [p, t] of walk(P.color, [])) L.push(`  ${name(p)}: ${oklch(t.$value)};`);
for (const [p, t] of walk(P.size, [])) L.push(`  ${name(["size", ...p])}: ${rem(t.$value)};`);
for (const [p, t] of walk(P.radius, [])) L.push(`  ${name(["radius", ...p])}: ${rem(t.$value)};`);
for (const [p, t] of walk(P.stroke, [])) L.push(`  ${name(["stroke", ...p])}: ${t.$value}px;`);
for (const [p, t] of walk(P.font, [])) {
  const v = t.$type !== "dimension" ? val(t) : p[0] === "tracking" ? `${t.$value}px` : rem(t.$value);
  L.push(`  ${name(["font", ...p])}: ${v};`);
}
L.push("}", "");

// Tier 2 color (themed)
const sem = (path) => path.join("-");
for (const [p, t] of walk(tokens.color, [])) {
  const m = t.$extensions?.mode ?? { Light: t.$value, Dark: t.$value };
  light.push(`  --sg-${sem(p)}: ${ref(m.Light)};`);
  dark.push(`  --sg-${sem(p)}: ${ref(m.Dark)};`);
}
L.push("/* Tier 2: semantic color. What components use. Switches with the theme. */", ':root, [data-theme="light"] {', ...light, "}", "", '[data-theme="dark"] {', ...dark, "}", "");

// Tier 2 dimension + type (unthemed)
L.push("/* Tier 2: semantic dimension and type. */", ":root {");
const D = tokens.dimension;
const pref = (s) => s.replace(/\{primitives\.(size|radius|stroke)\.([^}]+)\}/, (_, g, k) => `var(--sg-${g}-${k})`);
for (const [p, t] of walk(D, [])) L.push(`  --sg-${sem(p)}: ${pref(t.$value)};`);
const T = tokens.type;
for (const [p, t] of walk(T.text, [])) {
  if (p[0] === "family" || p[0] === "weight") { L.push(`  --sg-text-${sem(p)}: var(--sg-font-${sem(p)});`); continue; }
  const [step, prop] = p;
  const size = T.text[step].size.$value;
  const v = prop === "size" ? rem(t.$value) : prop === "line-height" ? rem(t.$value) : em(t.$value, size);
  L.push(`  --sg-text-${step}-${prop}: ${v};`);
}
for (const [role, r] of Object.entries(T.type)) {
  const fam = r.family.$value.match(/family\.(\w+)/)[1];
  const lh = +(r["line-height"].$value / r.size.$value).toFixed(3);
  L.push(`  --sg-type-${role}: ${r.weight.$value} ${rem(r.size.$value)} / ${lh} var(--sg-font-family-${fam});`);
  L.push(`  --sg-type-${role}-tracking: ${em(r.tracking.$value, r.size.$value)};`);
}
L.push("}", "");

writeFileSync(root + "src/generated.css", L.join("\n"));
console.log(`tokens: wrote src/generated.css (${L.length} lines)`);
